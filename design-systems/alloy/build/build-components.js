#!/usr/bin/env node
/**
 * Component-CSS bundler — the second half of the unified `npm run build`.
 *
 * Concatenates each kit's co-located component CSS (components/<Name>/<Name>.css)
 * into a generated, do-not-edit per-kit bundle:
 *
 *   global-kit/dist/global-kit.css      (core component library)
 *   product-kits/<p>/dist/<p>.css       (product-specific compositions only)
 *
 * Each bundle @imports the token layer so a single <link> delivers
 * fonts + primitives + token layers + component styles.
 *
 * Component CSS must bind only to token custom properties (var(--…)); this
 * bundler does not transform values — it just orders and concatenates.
 * No dependencies — plain Node.
 */
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const natCmp = (a, b) => String(a).localeCompare(String(b), undefined, { numeric: true, sensitivity: 'base' });

// Recursively collect *.css under a components/ dir, as { name, file, css }.
function collectCss(componentsDir) {
  const out = [];
  const walk = (dir) => {
    let entries = [];
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.isFile() && e.name.toLowerCase().endsWith('.css')) {
        out.push({ name: e.name.replace(/\.css$/i, ''), rel: path.relative(componentsDir, full), css: fs.readFileSync(full, 'utf8').trim() });
      }
    }
  };
  walk(componentsDir);
  return out.sort((a, b) => natCmp(a.rel, b.rel));
}

const banner = (kit) => `/* ======================================================================\n`
  + `   GENERATED by build/build-components.js — DO NOT EDIT.\n`
  + `   Kit: ${kit}. Edit the co-located component CSS, then run: npm run build\n`
  + `   ====================================================================== */\n`;

// kit definitions: label, componentsDir, distFile, leading @imports
const REL = (from, to) => { const r = path.relative(path.dirname(from), to).split(path.sep).join('/'); return r.startsWith('.') ? r : './' + r; };
const TOKENS = path.join(REPO, 'tokens', 'dist', 'tokens.css');
const GLOBAL_BUNDLE = path.join(REPO, 'global-kit', 'dist', 'global-kit.css');

const kits = [
  { label: 'global-kit', componentsDir: path.join(REPO, 'global-kit', 'components'), dist: GLOBAL_BUNDLE, imports: (out) => [TOKENS] },
];
for (const p of ['arc', 'drp', 'drs', 'drsc', 't1', 'arc-consumer']) {
  kits.push({
    label: `product-kits/${p}`,
    componentsDir: path.join(REPO, 'product-kits', p, 'components'),
    dist: path.join(REPO, 'product-kits', p, 'dist', `${p}.css`),
    imports: () => [TOKENS, GLOBAL_BUNDLE], // products build on the Global Kit
  });
}

const report = { bundles: {} };
for (const kit of kits) {
  const comps = collectCss(kit.componentsDir);
  if (!comps.length) { report.bundles[kit.label] = 0; continue; } // nothing to bundle yet
  fs.mkdirSync(path.dirname(kit.dist), { recursive: true });
  const importLines = kit.imports().map((t) => `@import "${REL(kit.dist, t)}";`).join('\n');
  const body = comps.map((c) => `/* ---- ${c.name} (${c.rel}) ---- */\n${c.css}`).join('\n\n');
  fs.writeFileSync(kit.dist, `${banner(kit.label)}\n${importLines}\n\n${body}\n`);
  report.bundles[kit.label] = comps.length;
}

console.log('Component CSS build complete.');
console.log(JSON.stringify(report, null, 2));
