#!/usr/bin/env node
/**
 * Walks assets/icons/{chevy,buick,gmc,cadillac,shared}/*.svg and emits
 * styles/icons.css — one base class per icon plus [data-brand] overrides.
 *
 * Chevy is the base brand. Every .drp-icon--<name> rule points at the
 * chevy SVG; [data-brand="buick|gmc|cadillac"] rules override with the
 * matching brand SVG. Shared icons (no brand prefix) render the same
 * everywhere.
 *
 * Vite inlines each SVG as a base64 data URI at build time (files are
 * well under assetsInlineLimit = 4096 bytes), so the built CSS is a
 * single request — no 400+ SVG waterfall.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const ICONS_DIR = path.join(ROOT, 'assets/icons')
const OUT = path.join(ROOT, 'styles/icons.css')

const BRANDS = ['chevy', 'buick', 'gmc', 'cadillac']

const listIcons = (brandDir) =>
  fs.readdirSync(brandDir)
    .filter((f) => f.endsWith('.svg'))
    .map((f) => f.replace(/\.svg$/, ''))
    .sort()

const chevyIcons = listIcons(path.join(ICONS_DIR, 'chevy'))
const sharedIcons = fs.existsSync(path.join(ICONS_DIR, 'shared'))
  ? listIcons(path.join(ICONS_DIR, 'shared'))
  : []

const lines = []
lines.push('/* AUTO-GENERATED by scripts/generate-icon-css.mjs — DO NOT EDIT BY HAND. */')
lines.push('/* Source: assets/icons/<brand>/<name>.svg. Regenerate: npm run generate:icons */')
lines.push('')
lines.push('.drp-icon {')
lines.push('  display: inline-block;')
lines.push('  width: 1em;')
lines.push('  height: 1em;')
lines.push('  background-color: currentColor;')
lines.push('  -webkit-mask-size: contain; mask-size: contain;')
lines.push('  -webkit-mask-repeat: no-repeat; mask-repeat: no-repeat;')
lines.push('  -webkit-mask-position: center; mask-position: center;')
lines.push('  vertical-align: -0.125em;')
lines.push('  flex-shrink: 0;')
lines.push('}')
lines.push('')
lines.push('/* ===== Base (Chevrolet) ===== */')
for (const name of chevyIcons) {
  const url = `url("../assets/icons/chevy/${name}.svg")`
  lines.push(`.drp-icon--${name} { -webkit-mask-image: ${url}; mask-image: ${url}; }`)
}

for (const brand of BRANDS.slice(1)) {
  const brandDir = path.join(ICONS_DIR, brand)
  if (!fs.existsSync(brandDir)) continue
  const brandIcons = new Set(listIcons(brandDir))
  lines.push('')
  lines.push(`/* ===== ${brand[0].toUpperCase() + brand.slice(1)} overrides ===== */`)
  for (const name of chevyIcons) {
    if (!brandIcons.has(name)) continue
    const url = `url("../assets/icons/${brand}/${name}.svg")`
    lines.push(`[data-brand="${brand}"] .drp-icon--${name} { -webkit-mask-image: ${url}; mask-image: ${url}; }`)
  }
}

if (sharedIcons.length) {
  lines.push('')
  lines.push('/* ===== Shared (non-brand) ===== */')
  for (const name of sharedIcons) {
    const url = `url("../assets/icons/shared/${name}.svg")`
    lines.push(`.drp-icon--${name} { -webkit-mask-image: ${url}; mask-image: ${url}; }`)
  }
}

lines.push('')
fs.writeFileSync(OUT, lines.join('\n'))

const totalRules =
  chevyIcons.length +
  BRANDS.slice(1).reduce((acc, b) => {
    const dir = path.join(ICONS_DIR, b)
    return fs.existsSync(dir) ? acc + listIcons(dir).length : acc
  }, 0) +
  sharedIcons.length

console.log(`wrote ${path.relative(ROOT, OUT)}  (${chevyIcons.length} base icons, ${totalRules} total rules, ${sharedIcons.length} shared)`)
